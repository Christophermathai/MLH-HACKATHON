/**
 * Utility to convert Devanagari Unicode characters (0x0900..0x097F)
 * to Malayalam Unicode characters (0x0D00..0x0D7F).
 *
 * Whisper frequently outputs Indic phonemes in Devanagari script for low-resource languages
 * like Malayalam. This utility provides a lossless, deterministic mapping to Malayalam script.
 */

const DEV_TO_MAL_MAP: Record<number, number | null> = {
  // Signs
  0x0901: 0x0D01, // Candrabindu
  0x0902: 0x0D02, // Anusvara
  0x0903: 0x0D03, // Visarga

  // Independent Vowels
  0x0905: 0x0D05, // A
  0x0906: 0x0D06, // AA
  0x0907: 0x0D07, // I
  0x0908: 0x0D08, // II
  0x0909: 0x0D09, // U
  0x090A: 0x0D0A, // UU
  0x090B: 0x0D0B, // Vocalic R
  0x090C: 0x0D0C, // Vocalic L
  0x090D: 0x0D0E, // Candra E -> Short E
  0x090E: 0x0D0E, // Short E
  0x090F: 0x0D0E, // E -> Short E
  0x0910: 0x0D10, // AI
  0x0911: 0x0D12, // Candra O -> Short O
  0x0912: 0x0D12, // Short O
  0x0913: 0x0D12, // O -> Short O
  0x0914: 0x0D14, // AU

  // Consonants
  0x0915: 0x0D15, 0x0916: 0x0D16, 0x0917: 0x0D17, 0x0918: 0x0D18, 0x0919: 0x0D19,
  0x091A: 0x0D1A, 0x091B: 0x0D1B, 0x091C: 0x0D1C, 0x091D: 0x0D1D, 0x091E: 0x0D1E,
  0x091F: 0x0D1F, 0x0920: 0x0D20, 0x0921: 0x0D21, 0x0922: 0x0D22, 0x0923: 0x0D23,
  0x0924: 0x0D24, 0x0925: 0x0D25, 0x0926: 0x0D26, 0x0927: 0x0D27, 0x0928: 0x0D28,
  0x0929: 0x0D29,
  0x092A: 0x0D2A, 0x092B: 0x0D2B, 0x092C: 0x0D2C, 0x092D: 0x0D2D, 0x092E: 0x0D2E,
  0x092F: 0x0D2F, 0x0930: 0x0D30, 0x0931: 0x0D31, 0x0932: 0x0D32, 0x0933: 0x0D33,
  0x0934: 0x0D34, 0x0935: 0x0D35, 0x0936: 0x0D36, 0x0937: 0x0D37, 0x0938: 0x0D38,
  0x0939: 0x0D39,
  0x093C: null, // Drop nukta

  // Vowel signs (matras)
  0x093E: 0x0D3E, // aa
  0x093F: 0x0D3F, // i
  0x0940: 0x0D40, // ii
  0x0941: 0x0D41, // u
  0x0942: 0x0D42, // uu
  0x0943: 0x0D43, // r
  0x0944: 0x0D44, // rr
  0x0945: 0x0D46, // candra e -> short e
  0x0946: 0x0D46, // short e
  0x0947: 0x0D46, // e -> short e
  0x0948: 0x0D48, // ai
  0x0949: 0x0D4B, // candra o -> long o
  0x094A: 0x0D4A, // short o
  0x094B: 0x0D4B, // o
  0x094C: 0x0D57, // au length mark
  0x094D: 0x0D4D, // virama (chandrakkala)

  // Numerals
  0x0966: 0x0D66, 0x0967: 0x0D67, 0x0968: 0x0D68, 0x0969: 0x0D69, 0x096A: 0x0D6A,
  0x096B: 0x0D6B, 0x096C: 0x0D6C, 0x096D: 0x0D6D, 0x096E: 0x0D6E, 0x096F: 0x0D6F,

  // Danda & Double Danda
  0x0964: 0x002E, // '.'
  0x0965: 0x002E, // '.'
};

export function devanagariToMalayalam(text: string): string {
  if (!text) return text;
  let out = "";
  for (let i = 0; i < text.length; i++) {
    const cp = text.charCodeAt(i);
    if (cp in DEV_TO_MAL_MAP) {
      const mapped = DEV_TO_MAL_MAP[cp];
      if (mapped !== null && mapped !== undefined) {
        out += String.fromCharCode(mapped);
      }
    } else if (cp >= 0x0900 && cp <= 0x097F) {
      out += String.fromCharCode(cp + 0x0400);
    } else {
      out += text[i];
    }
  }

  return out
    .replace(/\u0d30\u0d4d(?=[\u0d15-\u0d39])/g, "\u0d7c")
    .replace(/\u0d41\u0d2e(?=$|[\s.,!?;:])/g, "\u0d41\u0d02")
    .replace(/\u0d3f\u0d32(?=$|[\s.,!?;:])/g, "\u0d3f\u0d7d")
    .replace(/\u0d3f\u0d28(?=$|[\s.,!?;:])/g, "\u0d3f\u0d28\u0d4d");
}
